def update_locale(locale_dir, values):
    filepath = os.path.join(LOCALES_DIR, locale_dir, "preferences.js")
    with open(filepath, "r", encoding="utf-8") as f:
        content = f.read()

    # Skip if already applied (idempotent for re-runs).
    if "m3u8-section-title" in content:
        print(f"[skip] {locale_dir} already has m3u8 keys")
        return

    # Insert immediately after the 'ffmpeg-required' line.
    anchor = "'ffmpeg-required': '"
    idx = content.find(anchor)
    if idx == -1:
        raise SystemExit(f"[error] anchor 'ffmpeg-required' missing in {filepath}")

    line_end = content.find("\n", idx)
    insertion = []
    for key in (
        "m3u8-section-title",
        "m3u8-max-retries",
        "m3u8-max-retries-hint",
        "m3u8-retry-delay",
        "m3u8-retry-delay-hint",
        "m3u8-segment-timeout",
        "m3u8-segment-timeout-hint",
        "m3u8-concurrency",
        "m3u8-concurrency-hint",
        "m3u8-auto-cleanup",
        "m3u8-auto-cleanup-hint",
    ):
        value = values[key].replace("\\", "\\\\").replace("'", "\\'")
        # Match the two-space indentation used by existing keys.
        insertion.append(f"  '{key}': '{value}',")

    insert_at = line_end + 1  # start of the following line
    new_content = content[:insert_at] + "\n".join(insertion) + "\n" + content[insert_at:]
    with open(filepath, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)
    print(f"[ok] {locale_dir}: inserted {len(insertion)} keys")


for locale_dir, values in sorted(TRANSLATIONS.items()):
    update_locale(locale_dir, values)

print("Done.")